#!/usr/bin/env python3
"""Generate src/fonts.cpp from the Courier Prime font the Pi version uses.

Usage: python3 tools/gen_font.py [path-to-Courier-Prime.ttf]

For each size the Pi uses (18, 20, 26, 28, 32 px) every ASCII glyph 32..126 is
rendered into a fixed monospace cell (width = round(0.6 * size), height =
ascent + descent + 1) and packed MSB-first, 1 = ink. The cell's top edge is
the font's ascender line, the same origin PIL's draw.text() uses, so layouts
match the Pi. Courier Prime is under the SIL Open Font License. Needs Pillow.
"""
import math
import os
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
TTF = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', '..', 'src', 'Courier Prime.ttf')
OUT = os.path.join(HERE, '..', 'src', 'fonts.cpp')
SIZES = [18, 20, 26, 28, 32]

out = ['// Generated by tools/gen_font.py from Courier Prime (SIL OFL). Do not edit.',
       '#include "fonts.h"', '']
clipped_total = 0
for size in SIZES:
    font = ImageFont.truetype(TTF, size)
    ascent, descent = font.getmetrics()
    w = int(round(0.6 * size))
    h = ascent + descent + 1
    rb = math.ceil(w / 8)
    glyphs = []
    for code in range(32, 127):
        big = Image.new('1', (w + 12, h + 12), 1)
        ImageDraw.Draw(big).text((0, 0), chr(code), font=font, fill=0)
        px = big.load()
        for y in range(big.size[1]):
            for x in range(w, big.size[0]):
                if px[x, y] == 0 and x >= w:
                    clipped_total += 1
        data = []
        for y in range(h):
            bits = 0
            for x in range(rb * 8):
                bits = (bits << 1) | (1 if x < w and px[x, y] == 0 else 0)
            data.extend(bits.to_bytes(rb, 'big'))
        glyphs.append((code, data))
    out.append(f'static const uint8_t G{size}[95 * {h * rb}] = {{')
    for code, data in glyphs:
        out.append('  ' + ','.join(str(b) for b in data) + f',  // {code}')
    out.append('};')
    out.append(f'const Font FONT_{size} = {{{w}, {h}, {rb}, {ascent}, G{size}}};')
    out.append('')
with open(OUT, 'w') as f:
    f.write('\n'.join(out))
print('wrote', os.path.normpath(OUT), '(ink pixels beyond a cell, clipped: %d)' % clipped_total)
