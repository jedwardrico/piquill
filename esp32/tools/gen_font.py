#!/usr/bin/env python3
"""Generate src/font_courier28.h from the Courier Prime font the Pi version uses.

Usage: python3 tools/gen_font.py [path-to-Courier-Prime.ttf]

Each ASCII glyph 32..126 is rendered at 28 px into a fixed 17x36 cell (the same
size and line height as the Pi version: font size 28, line spacing 36) and packed
MSB-first, 3 bytes per row, 1 = ink. Courier Prime is under the SIL Open Font
License. Needs Pillow.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
TTF = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', '..', 'src', 'Courier Prime.ttf')
OUT = os.path.join(HERE, '..', 'src', 'font_courier28.h')
SIZE, W, H, ROW_BYTES = 28, 17, 36, 3

font = ImageFont.truetype(TTF, SIZE)
rows = []
for code in range(32, 127):
    img = Image.new('1', (W, H), 1)
    ImageDraw.Draw(img).text((0, 0), chr(code), font=font, fill=0)
    px = img.load()
    data = []
    for y in range(H):
        bits = 0
        for x in range(ROW_BYTES * 8):
            bits = (bits << 1) | (1 if x < W and px[x, y] == 0 else 0)
        data.extend(bits.to_bytes(ROW_BYTES, 'big'))
    rows.append((code, data))

with open(OUT, 'w') as f:
    f.write('// Generated by tools/gen_font.py from Courier Prime (SIL OFL). Do not edit.\n')
    f.write('#pragma once\n#include <stdint.h>\n\n')
    f.write('namespace font {\n')
    f.write(f'constexpr int CELL_W = {W};\nconstexpr int CELL_H = {H};\n')
    f.write(f'constexpr int ROW_BYTES = {ROW_BYTES};\nconstexpr int FIRST = 32;\nconstexpr int LAST = 126;\n')
    f.write(f'// 1 = ink. {H} rows of {ROW_BYTES} bytes per glyph, MSB first.\n')
    f.write(f'static const uint8_t GLYPHS[{len(rows)}][{H * ROW_BYTES}] = {{\n')
    for code, data in rows:
        f.write('  {' + ','.join(str(b) for b in data) + f'}},  // {code} {chr(code)!r}\n')
    f.write('};\n}  // namespace font\n')
print('wrote', os.path.normpath(OUT))
