#!/usr/bin/env python3
"""Generate src/fonts.cpp from EB Garamond Bold (a proportional font).

Usage: python3 tools/gen_font.py [path-to-EBGaramond-VF.ttf]

For each size every ASCII glyph 32..126 is rendered (Bold instance of the
variable font, 1 bit per pixel, anything under 41% ink is white) and cropped to
its own ink width. Per glyph we store the advance, the left bearing and the
bitmap, packed MSB-first, 1 = ink, one row = ceil(width / 8) bytes. All glyphs
of a size share one cell height: the tallest ink above and lowest ink below the
baseline over the whole set, so a line of text needs only `h` rows. There is no
kerning. EB Garamond is under the SIL Open Font License (tools/fonts/). Needs
Pillow with FreeType variable-font support.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
TTF = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'fonts', 'EBGaramond-VF.ttf')
OUT = os.path.join(HERE, '..', 'src', 'fonts.cpp')
SIZES = [20, 22, 30, 32, 36]
PAD = 16  # room left of the origin for negative bearings, and above/below

out = ['// Generated by tools/gen_font.py from EB Garamond Bold (SIL OFL). Do not edit.',
       '#include "fonts.h"', '']
for size in SIZES:
    font = ImageFont.truetype(TTF, size)
    font.set_variation_by_name('Bold')
    ascent, descent = font.getmetrics()
    cw, ch = size * 3, ascent + descent + 2 * PAD
    glyphs = []  # (code, advance, xoff, w, rows) rows = list of bit-lists, full canvas height
    top, bottom = ch, 0
    for code in range(32, 127):
        c = chr(code)
        img = Image.new('L', (cw, ch), 255)
        ImageDraw.Draw(img).text((PAD, PAD), c, font=font, fill=0)
        ink = img.point(lambda v: 255 if v < 150 else 0)  # 255 = ink
        bbox = ink.getbbox()
        adv = int(round(font.getlength(c)))
        if bbox is None:
            glyphs.append((code, adv, 0, 0, None))
            continue
        x0, y0, x1, y1 = bbox
        top, bottom = min(top, y0), max(bottom, y1)
        glyphs.append((code, adv, x0 - PAD, x1 - x0, ink.crop((x0, 0, x1, ch))))
    h = bottom - top
    base = PAD + ascent - top  # baseline row inside the cropped cell
    info, data = [], []
    for code, adv, xoff, w, im in glyphs:
        info.append('{%d,%d,%d,%d}' % (len(data), adv, xoff, w))
        if im is None:
            continue
        px = im.load()
        rb = (w + 7) // 8
        for y in range(top, bottom):
            bits = 0
            for x in range(rb * 8):
                bits = (bits << 1) | (1 if x < w and px[x, y] else 0)
            data.extend(bits.to_bytes(rb, 'big'))
    out.append(f'static const GlyphInfo I{size}[95] = {{')
    for i in range(0, 95, 6):
        out.append('  ' + ','.join(info[i:i + 6]) + ',')
    out.append('};')
    out.append(f'static const uint8_t B{size}[{len(data)}] = {{')
    for i in range(0, len(data), 24):
        out.append('  ' + ','.join(str(b) for b in data[i:i + 24]) + ',')
    out.append('};')
    out.append(f'const Font FONT_{size} = {{{h}, {base}, I{size}, B{size}}};')
    out.append('')
    print(f'size {size}: cell height {h}, baseline row {base}, {len(data)} bytes')
with open(OUT, 'w') as f:
    f.write('\n'.join(out))
print('wrote', os.path.normpath(OUT))
